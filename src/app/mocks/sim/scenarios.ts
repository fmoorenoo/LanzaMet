/*
 * DEMO DATA — weather "stories" for the simulator. Each scenario describes the
 * island-wide pattern for seven days (today first). Places then bend it with
 * their own exposure, so the north and the south rarely agree.
 */

export type ScenarioId = 'alisio' | 'calma' | 'ventoso' | 'calima' | 'borrasca';

export interface ScenarioDay {
  /** Island average temperature at mid-afternoon. */
  readonly maxC: number;
  /** Day–night swing. */
  readonly rangeC: number;
  readonly windKmh: number;
  readonly windFrom: number;
  readonly swellM: number;
  readonly swellFrom: number;
  /** Base cloud cover 0–1. */
  readonly clouds: number;
  /** Saharan dust 0–1. */
  readonly haze: number;
  /** Chance of showers 0–1. */
  readonly rain: number;
}

export interface Scenario {
  readonly id: ScenarioId;
  readonly name: string;
  readonly description: string;
  readonly days: readonly ScenarioDay[];
}

const day = (d: ScenarioDay): ScenarioDay => d;

